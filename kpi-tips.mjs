/** 그 지표의 두 줄 설명(줄바꿈으로 이음) — 없으면 ''. graceHours = 학부모 열람 판정 유예(판정이 쓰는 값 그대로). */
export function kpiTip(id, { graceHours = 48 } = {}) {
  const t = TIPS[id]; if (!t) return '';
  return t.map(x => (typeof x === 'function' ? x(graceHours) : x)).join('\n');
}
