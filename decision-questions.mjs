/** Same questions with the work_area options reversed, for the option-order robustness check. */
export function reversedAreaQuestions() {
  const { work_area: area, ...rest } = QUESTIONS;
  return { ...rest, work_area: { ...area, criteria: Object.fromEntries(Object.entries(area.criteria).reverse()) } };
}
