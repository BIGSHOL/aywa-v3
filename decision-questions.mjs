// Bounded decision questions and context validation for academy work routing.
// The caller supplies redacted facts; this module builds the Jev state from them.
// Identifiers, candidate staff and relationships never enter the state: code, not
// Jev, resolves who may do the work. Date arithmetic is done here (Jev reads dates as text).
export const QUESTIONS_VERSION = 'owner-decision-q1';
export const AREAS = Object.freeze(['attendance', 'billing', 'academic', 'counseling', 'enrollment', 'schedule', 'staff_hr', 'operations', 'none', 'unclear']);
export const SOURCES = Object.freeze({ parent_message: 'message from a parent', staff_note: 'note written by a staff member', system_event: 'event generated by the academy system', consultation_note: 'consultation record', task_comment: 'comment on an internal task' });
// Granular roles come from DB relationships (homeroom/class teaching/billing duty). Generic flow roles
// (teacher/staff) are accepted as lower-priority fallbacks; see AI-DECISIONS.md for the mapping.
export const ROLES = Object.freeze(['homeroom_teacher', 'subject_teacher', 'teacher', 'desk', 'billing', 'staff', 'manager', 'owner']);
export const WORK_AREAS = Object.freeze(AREAS.filter(a => a !== 'none' && a !== 'unclear'));
const LIMITS = Object.freeze({ text: 1500, threadText: 500, thread: 5, facts: 12, factKey: 40, factValue: 120, candidates: 20, id: 64, openWork: 5 });
// Unredacted contact/identity numbers must never leave the server.
const SENSITIVE = [/01[016789][-\s.]?\d{3,4}[-\s.]?\d{4}/, /\d{6}[-\s]?[1-4]\d{6}/, /\d{2,6}-\d{2,6}-\d{4,8}/, /\d{11,}/, /[\w.+-]+@[\w-]+\.[\w.]+/];

const isDate = v => typeof v === 'string' && /^\d{4}-\d{2}-\d{2}$/.test(v) && new Date(`${v}T00:00:00Z`).toISOString().slice(0, 10) === v;
const daysBetween = (from, to) => Math.round((Date.parse(`${to}T00:00:00Z`) - Date.parse(`${from}T00:00:00Z`)) / 86_400_000);
const isPlain = v => typeof v === 'object' && v !== null && !Array.isArray(v);
const str = (v, max, min = 0) => typeof v === 'string' && v.trim().length >= min && v.length <= max;

/** Returns { ok: true, value } or { ok: false, issues: [code] }. Issue codes never echo input text. */
export function validateContext(raw) {
  const issues = [];
  if (!isPlain(raw)) return { ok: false, issues: ['context_not_object'] };
  if (!str(raw.recordId, LIMITS.id, 1)) issues.push('record_id');
  if (!Object.hasOwn(SOURCES, raw.source)) issues.push('source');
  if (!isDate(raw.today)) issues.push('today');
  if (!isDate(raw.recordDate)) issues.push('record_date');
  if (raw.text != null && !str(raw.text, LIMITS.text)) issues.push('text');
  const thread = raw.thread ?? [];
  if (!Array.isArray(thread) || thread.length > LIMITS.thread || !thread.every(m => isPlain(m) && isDate(m.date) && str(m.text, LIMITS.threadText, 1))) issues.push('thread');
  const facts = raw.facts ?? {};
  if (!isPlain(facts) || Object.keys(facts).length > LIMITS.facts || !Object.entries(facts).every(([k, v]) => /^[a-z][a-z0-9_]*$/.test(k) && k.length <= LIMITS.factKey
    && (typeof v === 'boolean' || (typeof v === 'number' && Number.isFinite(v)) || str(v, LIMITS.factValue)))) issues.push('facts');
  const links = raw.links ?? {};
  if (!isPlain(links) || !Object.entries(links).every(([k, v]) => ['student', 'class', 'invoice', 'staff'].includes(k) && typeof v === 'boolean')) issues.push('links');
  const openWork = raw.knownOpenWork ?? [];
  if (!Array.isArray(openWork) || openWork.length > LIMITS.openWork || !openWork.every(w => isPlain(w) && WORK_AREAS.includes(w.area) && /^[a-z][a-z0-9_]{0,39}$/.test(w.code))) issues.push('known_open_work');
  const candidates = raw.candidates ?? [];
  if (!Array.isArray(candidates) || candidates.length > LIMITS.candidates || !candidates.every(c => isPlain(c) && str(c.staffId, LIMITS.id, 1)
    && Array.isArray(c.roles) && c.roles.length > 0 && c.roles.every(r => ROLES.includes(r)))) issues.push('candidates');
  if (!issues.length && raw.recordDate > raw.today) issues.push('record_date_in_future');
  if (issues.length) return { ok: false, issues };
  const texts = [raw.text ?? '', ...thread.map(m => m.text), ...Object.values(facts).filter(v => typeof v !== 'boolean').map(String)];
  if (texts.some(t => SENSITIVE.some(re => re.test(t)))) return { ok: false, issues: ['unredacted_content'] };
  return { ok: true, value: { recordId: raw.recordId, source: raw.source, today: raw.today, recordDate: raw.recordDate, text: (raw.text ?? '').trim(),
    thread: thread.map(m => ({ date: m.date, text: m.text.trim() })), facts: { ...facts }, links: { ...links },
    knownOpenWork: openWork.map(w => ({ area: w.area, code: w.code })),
    candidates: candidates.map(c => ({ staffId: c.staffId, roles: [...new Set(c.roles)], relation: typeof c.relation === 'string' ? c.relation.slice(0, 40) : null })) } };
}

/** True when there is nothing for Jev to read (no text, thread, facts or known open work): decided by code, not AI. */
export const hasNoContent = ctx => !ctx.text && !ctx.thread.length && !Object.keys(ctx.facts).length && !ctx.knownOpenWork.length;

const when = (date, today) => { const d = daysBetween(date, today); return d === 0 ? 'today' : d === 1 ? 'yesterday' : `${d} days before today`; };

/** Jev state: only what the questions need. No ids, no candidates, no staff. */
export function buildState(ctx) {
  return {
    today: ctx.today,
    record: {
      kind: SOURCES[ctx.source], date: ctx.recordDate, written: when(ctx.recordDate, ctx.today), text: ctx.text || '(no text)',
      earlier_messages_in_same_thread: ctx.thread.map(m => ({ date: m.date, written: when(m.date, ctx.today), text: m.text })),
      known_facts: ctx.facts, linked_records: ctx.links,
      unresolved_items_found_in_records: ctx.knownOpenWork.map(w => `${w.area}: ${w.code.replaceAll('_', ' ')}`),
    },
  };
}

